"""Fixture data in the contract's canonical model, seeded from the official dump (734 rows, 29 columns).

Website A (MySQL `web_legacy`): one wide table `anggota` with the dump's exact Indonesian column names (+ surrogate id).
Website B (PostgreSQL `web_modern`): the normalised English schema, plus the synthetic tables the contract adds
(`member_health`, `member_activities` with the detector traps: ref_code holds the NIK, notes hide phone/address).
Synthetic additions use a fixed seed, so every reset yields the same data. Login passwords are random per reset
and written to .local/credentials.json (never printed, never committed).
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import random
import secrets
from pathlib import Path

from .config import LOCAL, settings
from .sqldump import read_dump

ROLES = ["humas", "keuangan", "sdm", "medis", "admin", "anggota"]   # "public" = not logged in

A_DDL = """CREATE TABLE anggota (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(255) NOT NULL, nama_lengkap VARCHAR(255) NOT NULL, nama_tanpa_gelar VARCHAR(255) NOT NULL,
  jenis_kelamin VARCHAR(1) NOT NULL, tempat_lahir VARCHAR(255) NOT NULL, tanggal_lahir DATE NOT NULL,
  tanggal_pernikahan DATE NULL, no_ktp VARCHAR(255) NOT NULL, pekerjaan_terakhir VARCHAR(255) NOT NULL,
  alamat_jakarta VARCHAR(255) NOT NULL, telpon_jakarta VARCHAR(255) NOT NULL, alamat_daerah VARCHAR(255) NOT NULL,
  telpon_daerah VARCHAR(255) NOT NULL, handphone VARCHAR(255) NOT NULL, email VARCHAR(255) NOT NULL,
  ruangan VARCHAR(255) NOT NULL, status_kawin VARCHAR(2) NOT NULL, jumlah_anak SMALLINT NOT NULL,
  jumlah_tanggungan SMALLINT NOT NULL, jumlah_jiwa SMALLINT NOT NULL, rekening VARCHAR(255) NOT NULL,
  nama_rekening VARCHAR(255) NOT NULL, npwp VARCHAR(255) NOT NULL, nama_kppn VARCHAR(255) NOT NULL,
  nip_kppn VARCHAR(255) NOT NULL, nama_bank VARCHAR(255) NOT NULL, kode_bank VARCHAR(3) NOT NULL,
  pengguna VARCHAR(255) NOT NULL, agama VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"""

B_DDL = """
CREATE TABLE members (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, full_name text NOT NULL,
  display_name text NOT NULL, gender char(1) NOT NULL, birth_place text NOT NULL, birth_date date NOT NULL,
  job text NOT NULL, religion text NOT NULL, marital_status text NOT NULL, marriage_date date,
  room_code text NOT NULL, created_at timestamptz NOT NULL);
CREATE TABLE member_contacts (member_id integer PRIMARY KEY REFERENCES members(id), address_jakarta text NOT NULL,
  phone_jakarta text NOT NULL, address_region text NOT NULL, phone_region text NOT NULL, mobile text NOT NULL,
  email text NOT NULL);
CREATE TABLE member_finance (member_id integer PRIMARY KEY REFERENCES members(id), nik text NOT NULL, npwp text NOT NULL,
  account_no text NOT NULL, account_name text NOT NULL, bank_name text NOT NULL, bank_code text NOT NULL,
  kppn_name text NOT NULL, kppn_nip text NOT NULL);
CREATE TABLE member_family (member_id integer PRIMARY KEY REFERENCES members(id), num_children smallint NOT NULL,
  num_dependents smallint NOT NULL, num_souls smallint NOT NULL);
CREATE TABLE member_health (member_id integer PRIMARY KEY REFERENCES members(id), blood_type text NOT NULL,
  allergy_note text NOT NULL, condition_note text NOT NULL);
CREATE TABLE member_activities (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id integer NOT NULL REFERENCES members(id), title text NOT NULL, ref_code text NOT NULL, notes text NOT NULL,
  created_at timestamptz NOT NULL);
CREATE TABLE users (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username text NOT NULL UNIQUE,
  password_hash text NOT NULL, role text NOT NULL, member_id integer REFERENCES members(id));
"""

_BLOOD = ["O+", "A+", "B+", "AB+", "O-", "A-", "B-", "AB-"]
_BLOOD_W = [38, 27, 24, 6, 2, 1, 1, 1]
_ALLERGY = ["Tidak ada", "Tidak ada", "Tidak ada", "Alergi penisilin", "Alergi udang", "Alergi debu", "Alergi kacang"]
_CONDITION = ["Tidak ada keluhan", "Tidak ada keluhan", "Hipertensi terkontrol", "Diabetes tipe 2",
              "Pasca operasi lutut 2024", "Asma ringan", "Kolesterol tinggi"]
_TITLES = ["Kunjungan kerja dapil", "Rapat dengar pendapat", "Reses masa sidang", "Rapat komisi",
           "Penyerapan aspirasi", "Kunjungan spesifik"]
_NOTES = [
    "Koordinasi dengan sekretariat komisi, bahan rapat sudah dikirim.",
    "Hubungi ajudan di {mobile} untuk konfirmasi jadwal.",
    "Penjemputan di {address} pukul 07.00.",
    "Kirim undangan ke {email}; konfirmasi kehadiran via {mobile}.",
    "Notulen menyusul, tidak ada tindak lanjut khusus.",
    "Titik kumpul rombongan: {address}.",
]


def _pbkdf2(password: str) -> str:
    salt = secrets.token_bytes(16)
    dk = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, 200_000)
    return f"pbkdf2_sha256$200000${salt.hex()}${dk.hex()}"


def dump_rows(path: Path | None = None) -> tuple[list[str], list[list]]:
    t = read_dump(path or settings().seed_dump)["anggota"]
    return t["columns"], t["rows"]


def to_canonical(cols: list[str], rows: list[list], seed: int = 2026) -> dict[str, list[dict]]:
    """The contract's mapping dump -> website B tables, plus synthetic health and activities."""
    rng = random.Random(seed)
    out: dict[str, list[dict]] = {k: [] for k in ["members", "member_contacts", "member_finance", "member_family",
                                                     "member_health", "member_activities"]}
    base = dt.datetime(2024, 10, 1, 8, 0, tzinfo=dt.timezone(dt.timedelta(hours=7)))
    for i, r in enumerate(rows, start=1):
        a = dict(zip(cols, r))
        out["members"].append(dict(id=i, full_name=a["nama"], display_name=a["nama_tanpa_gelar"], gender=a["jenis_kelamin"],
                                   birth_place=a["tempat_lahir"], birth_date=a["tanggal_lahir"], job=a["pekerjaan_terakhir"],
                                   religion=a["agama"], marital_status=a["status_kawin"], marriage_date=a["tanggal_pernikahan"],
                                   room_code=a["ruangan"], created_at=base + dt.timedelta(hours=i)))
        out["member_contacts"].append(dict(member_id=i, address_jakarta=a["alamat_jakarta"], phone_jakarta=a["telpon_jakarta"],
                                           address_region=a["alamat_daerah"], phone_region=a["telpon_daerah"],
                                           mobile=a["handphone"], email=a["email"]))
        out["member_finance"].append(dict(member_id=i, nik=a["no_ktp"], npwp=a["npwp"], account_no=a["rekening"],
                                          account_name=a["nama_rekening"], bank_name=a["nama_bank"], bank_code=a["kode_bank"],
                                          kppn_name=a["nama_kppn"], kppn_nip=a["nip_kppn"]))
        out["member_family"].append(dict(member_id=i, num_children=a["jumlah_anak"], num_dependents=a["jumlah_tanggungan"],
                                         num_souls=a["jumlah_jiwa"]))
        out["member_health"].append(dict(member_id=i, blood_type=rng.choices(_BLOOD, _BLOOD_W)[0],
                                         allergy_note=rng.choice(_ALLERGY), condition_note=rng.choice(_CONDITION)))
        for _ in range(rng.randint(2, 4)):
            note = rng.choice(_NOTES).format(mobile=a["handphone"], address=a["alamat_daerah"], email=a["email"])
            out["member_activities"].append(dict(member_id=i, title=rng.choice(_TITLES), ref_code=a["no_ktp"], notes=note,
                                                 created_at=base + dt.timedelta(days=rng.randint(0, 360), hours=rng.randint(0, 9))))
    return out


def load_website_a(cols: list[str], rows: list[list]) -> int:
    from .db import MYSQL_DB, mysql_connect
    with mysql_connect(database=None) as c, c.cursor() as cur:
        cur.execute(f"DROP DATABASE IF EXISTS {MYSQL_DB}")
        cur.execute(f"CREATE DATABASE {MYSQL_DB} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci")
        cur.execute(f"USE {MYSQL_DB}")
        cur.execute(A_DDL)
        cur.executemany(f"INSERT INTO anggota ({', '.join(cols)}) VALUES ({', '.join(['%s'] * len(cols))})", rows)
        c.commit()
        cur.execute("SELECT COUNT(*) FROM anggota")
        return cur.fetchone()[0]


def load_website_b(data: dict[str, list[dict]], passwords: dict[str, str]) -> dict[str, int]:
    from .db import PG_DB, pg_connect
    with pg_connect(database="postgres") as admin:
        admin.autocommit = True
        admin.execute(f"DROP DATABASE IF EXISTS {PG_DB} WITH (FORCE)")
        admin.execute(f"CREATE DATABASE {PG_DB}")
    counts: dict[str, int] = {}
    with pg_connect() as c:
        c.execute(B_DDL)
        with c.cursor() as cur:
            for table, rows in data.items():
                cols = list(rows[0])
                with cur.copy(f"COPY {table} ({', '.join(cols)}) FROM STDIN") as cp:
                    for r in rows:
                        cp.write_row([r[k] for k in cols])
                counts[table] = len(rows)
            users = [(f"{role}1", _pbkdf2(passwords[f"{role}1"]), role, 1 if role == "anggota" else None) for role in ROLES]
            cur.executemany("INSERT INTO users (username, password_hash, role, member_id) VALUES (%s, %s, %s, %s)", users)
            counts["users"] = len(users)
            for t in ("members", "member_activities", "users"):   # identity columns continue after the loaded ids
                cur.execute(f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), (SELECT max(id) FROM {t}))")
    return counts


def load_all() -> dict[str, object]:
    cols, rows = dump_rows()
    passwords = {f"{r}1": secrets.token_urlsafe(18) for r in ROLES}
    LOCAL.mkdir(exist_ok=True)
    (LOCAL / "credentials.json").write_text(json.dumps(passwords, indent=2), encoding="utf-8")
    return {"website_a": {"anggota": load_website_a(cols, rows)}, "website_b": load_website_b(to_canonical(cols, rows), passwords)}
